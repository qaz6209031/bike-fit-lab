export const DICTS = { en, 'zh-TW': zh };
export const LANGS = [
  { code: 'en', short: 'EN', html: 'en' },
  { code: 'zh-TW', short: '繁中', html: 'zh-Hant-TW' },
];
const KEY = 'bikefit.lang';

/** Saved choice, else the browser's languages (any Chinese → zh-TW), else English. */
// Each language has its own URL so search engines can index both; the page pins its language.
export const PAGE_URLS = { en: '/', 'zh-TW': '/zh/' };

export function detectLang() {
  const pinned = globalThis.document?.documentElement?.dataset?.pageLang;
  if (pinned && DICTS[pinned]) return pinned;
  try {
    const saved = globalThis.window?.localStorage?.getItem(KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* storage blocked */ }
  const prefs = globalThis.navigator?.languages ?? [globalThis.navigator?.language].filter(Boolean);
  for (const l of prefs) {
    const p = l.toLowerCase();
    if (p.startsWith('zh')) return 'zh-TW';
    if (p.startsWith('en')) return 'en';
  }
  return 'en';
}

let lang = detectLang();
const listeners = new Set();

export const getLang = () => lang;
export const onLangChange = (fn) => listeners.add(fn);

export function setLang(code, { persist = true } = {}) {
  if (!DICTS[code]) return;
  lang = code;
  if (persist) {
    try { globalThis.window?.localStorage?.setItem(KEY, code); } catch { /* storage blocked */ }
  }
  listeners.forEach((fn) => fn(code));
}

export function t(key, params = {}) {
  const s = DICTS[lang][key] ?? en[key];
  if (s == null) {
    console.warn(`[i18n] missing key: ${key}`);
    return key;
  }
  if (typeof s === 'function') return s(params);
  return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] ?? m));
}

/** Fill elements marked with data-i18n (textContent), data-i18n-ph / -aria / -title (attributes). */
export function applyStatic(root = document) {
  const meta = LANGS.find((l) => l.code === lang);
  document.documentElement.lang = meta.html;
  const args = (el) => {
    try { return JSON.parse(el.dataset.i18nArgs || '{}'); } catch { return {}; }
  };
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n, args(el));
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
