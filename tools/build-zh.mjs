// Builds zh/index.html (the Traditional Chinese page at /zh/) from index.html and the zh-TW dictionary,
// so search engines get real Chinese text without JavaScript. Run after editing index.html or i18n.js:
//   node tools/build-zh.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { DICTS } = await import(pathToFileURL(join(root, 'i18n.js')).href);
const zh = DICTS['zh-TW'];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const escAttr = (s) => esc(s).replace(/"/g, '&quot;');
const fill = (s, args) => s.replace(/\{(\w+)\}/g, (m, k) => (args[k] ?? m));

let html = readFileSync(join(root, 'index.html'), 'utf8');
const missing = [];

// Text content of every translated element.
html = html.replace(/<(\w+)([^>]*?\sdata-i18n="([^"]+)"[^>]*)>([^<]*)<\/\1>/g, (m, tag, attrs, key) => {
  const v = zh[key];
  if (typeof v !== 'string') { missing.push(key); return m; }
  const argsAttr = attrs.match(/data-i18n-args='([^']*)'/);
  const args = argsAttr ? JSON.parse(argsAttr[1]) : {};
  return `<${tag}${attrs}>${esc(fill(v, args))}</${tag}>`;
});

// Translated attributes.
for (const [data, attr] of [['data-i18n-aria', 'aria-label'], ['data-i18n-ph', 'placeholder']]) {
  html = html.replace(new RegExp(`${data}="([^"]+)"([^>]*?)\\s${attr}="[^"]*"`, 'g'), (m, key, mid) => {
    const v = zh[key];
    if (typeof v !== 'string') { missing.push(key); return m; }
    return `${data}="${key}"${mid} ${attr}="${escAttr(v)}"`;
  });
}

// Page-level metadata.
const title = 'Free Bike Fit：免費線上 bike fit，用手機影片在家調整';
const desc = '免費線上 bike fit：從側面拍下你踩踏的影片，量出膝蓋、髖部、背部和手臂角度，告訴你坐墊高度、坐墊前後和把手距離該怎麼調。全部在瀏覽器裡完成。';
const ogDesc = '從側面拍下你踩踏的影片，看你的關節角度和該先調整什麼。全部在瀏覽器裡完成，影片不會離開你的裝置。';
const swaps = [
  [/<html lang="en" data-page-lang="en">/, '<html lang="zh-Hant-TW" data-page-lang="zh-TW">'],
  [/<title>[^<]*<\/title>/, `<title>${esc(title)}</title>`],
  [/(<meta name="description" content=")[^"]*/, `$1${escAttr(desc)}`],
  [/(<link rel="canonical" href=")[^"]*/, '$1https://freebikefit.com/zh/'],
  [/(<meta property="og:title" content=")[^"]*/, `$1${escAttr(title)}`],
  [/(<meta property="og:description" content=")[^"]*/, `$1${escAttr(ogDesc)}`],
  [/(<meta property="og:url" content=")[^"]*/, '$1https://freebikefit.com/zh/'],
  [/(<meta property="og:image" content=")[^"]*/, '$1https://freebikefit.com/og-image-zh.png'],
  [/(<meta property="og:image:alt" content=")[^"]*/, '$1Free Bike Fit：膝蓋角度 145 度，落在 140–150 度的目標範圍內'],
  [/<meta property="og:locale" content="en_US" \/>/, '<meta property="og:locale" content="zh_TW" />'],
  [/<meta property="og:locale:alternate" content="zh_TW" \/>/, '<meta property="og:locale:alternate" content="en_US" />'],
  [/"url": "https:\/\/freebikefit.com\/",/, '"url": "https://freebikefit.com/zh/",'],
  [/("description": ")Free online bike fit[^"]*/, `$1${desc}`],
  [/"inLanguage": \[[^\]]*\]/, '"inLanguage": "zh-TW"'],
  [/"image": "https:\/\/freebikefit.com\/og-image.png"/, '"image": "https://freebikefit.com/og-image-zh.png"'],
  // The English page sends Chinese readers here; this page must not send them anywhere.
  [/\s*<!-- Visitors who chose Chinese[^\n]*\n\s*<script id="langRedirect">[\s\S]*?<\/script>/, ''],
];
for (const [re, to] of swaps) {
  if (!re.test(html)) throw new Error(`build-zh: pattern not found: ${re}`);
  html = html.replace(re, to);
}

html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by tools/build-zh.mjs from index.html. Do not edit by hand. -->');
mkdirSync(join(root, 'zh'), { recursive: true });
writeFileSync(join(root, 'zh', 'index.html'), html);
if (missing.length) console.warn('No zh-TW string for:', [...new Set(missing)].join(', '));
console.log('Wrote zh/index.html');
